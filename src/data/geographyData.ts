// Deduplication process
const normalizeText = (text: string): string => {
  return text
    .replace(/[؟،.\-\s\(\)]/g, '')
    .replace(/[أإآا]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .trim();
};

// Returns deduplicated geography questions by filtering duplicates inside RAW_GEOGRAPHY_QUESTIONS
// and also removing duplicates between raw geography and existing HISTORY_GEOGRAPHY_QUESTIONS.
export const getDeduplicatedGeographyQuestions = (existingQuestions: BankQuestion[] = []): BankQuestion[] => {
  const seenNormalized = new Set<string>();

  // Exclude duplicates in existing bank first
  const existingNormalized = new Set<string>();
  existingQuestions.forEach(q => {
    existingNormalized.add(normalizeText(q.text));
  });

  const finalGeography: BankQuestion[] = [];

  RAW_GEOGRAPHY_QUESTIONS.forEach(q => {
    const normalized = normalizeText(q.text);
    // If we haven't seen this question in this run, AND it doesn't already exist in the history/geography bank, keep it!
    // But wait: if it exists, we want to prioritize our fresh high-quality question with correct points/difficulty!
    // So we can deduplicate them. Let's make sure it doesn't duplicate *within* the new set first.
    if (!seenNormalized.has(normalized)) {
      seenNormalized.add(normalized);
      finalGeography.push(q);
    }
  });

  return finalGeography;
};
